"""Converts the boot screen logo image into src/logo.h.

    python3 -I tools/logo2header.py assets/apple-logo.png src/logo.h [height] [preview.png]

The logo is whatever is strongly coloured in the image, so a white, grey or checkerboard
background and a dark screenshot frame are ignored. It is cropped, scaled to `height` pixels
(default 104) and stored as a 1-bit mask plus one RGB565 colour per row (the logo's stripes),
which is all the rainbow logo needs. An optional preview PNG of the result is written at 4x.
"""

import struct
import sys
import zlib


def read_png(path):
    data = open(path, "rb").read()
    assert data[:8] == b"\x89PNG\r\n\x1a\n", "not a PNG"
    pos, idat = 8, b""
    while pos < len(data):
        length, kind = struct.unpack(">I4s", data[pos:pos + 8])
        body = data[pos + 8:pos + 8 + length]
        if kind == b"IHDR":
            w, h, depth, ctype, _, _, interlace = struct.unpack(">IIBBBBB", body)
            assert depth == 8 and ctype in (2, 6) and interlace == 0, "needs 8-bit RGB/RGBA, not interlaced"
        elif kind == b"IDAT":
            idat += body
        pos += 12 + length
    bpp = 4 if ctype == 6 else 3
    raw = zlib.decompress(idat)
    stride = w * bpp
    rows, prev = [], bytearray(stride)
    for y in range(h):
        f = raw[y * (stride + 1)]
        line = bytearray(raw[y * (stride + 1) + 1:(y + 1) * (stride + 1)])
        for i in range(stride):
            a = line[i - bpp] if i >= bpp else 0
            b = prev[i]
            c = prev[i - bpp] if i >= bpp else 0
            if f == 1:
                line[i] = (line[i] + a) & 0xFF
            elif f == 2:
                line[i] = (line[i] + b) & 0xFF
            elif f == 3:
                line[i] = (line[i] + (a + b) // 2) & 0xFF
            elif f == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[i] = (line[i] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 0xFF
        rows.append([tuple(line[x * bpp:x * bpp + 3]) + ((line[x * bpp + 3],) if bpp == 4 else (255,))
                     for x in range(w)])
        prev = line
    return w, h, rows


def is_logo(px):
    r, g, b, a = px
    return a > 128 and max(r, g, b) - min(r, g, b) > 80


def write_png(path, w, h, pixel):
    raw = b"".join(b"\0" + b"".join(bytes(pixel(x, y)) for x in range(w)) for y in range(h))
    chunk = lambda t, d: struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d))
    open(path, "wb").write(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0))
                           + chunk(b"IDAT", zlib.compress(raw)) + chunk(b"IEND", b""))


def main():
    src, dst = sys.argv[1], sys.argv[2]
    out_h = int(sys.argv[3]) if len(sys.argv) > 3 else 104
    preview = sys.argv[4] if len(sys.argv) > 4 else None
    w, h, rows = read_png(src)

    mask = [[is_logo(px) for px in row] for row in rows]
    ys = [y for y in range(h) if any(mask[y])]
    xs = [x for x in range(w) if any(mask[y][x] for y in ys)]
    x0, x1, y0, y1 = xs[0], xs[-1] + 1, ys[0], ys[-1] + 1
    scale = (y1 - y0) / out_h
    out_w = round((x1 - x0) / scale)

    bits, colors = [], []
    for oy in range(out_h):
        sy0, sy1 = y0 + int(oy * scale), y0 + max(int((oy + 1) * scale), int(oy * scale) + 1)
        # The row's colour: the most common logo colour in its source rows
        counts = {}
        for sy in range(sy0, sy1):
            for sx in range(x0, x1):
                if mask[sy][sx]:
                    c = rows[sy][sx][:3]
                    counts[c] = counts.get(c, 0) + 1
        colors.append(max(counts, key=counts.get) if counts else (0, 0, 0))
        line = []
        for ox in range(out_w):
            sx0, sx1 = x0 + int(ox * scale), x0 + max(int((ox + 1) * scale), int(ox * scale) + 1)
            inside = sum(mask[sy][sx] for sy in range(sy0, sy1) for sx in range(sx0, sx1))
            line.append(inside * 2 >= (sy1 - sy0) * (sx1 - sx0))
        bits.append(line)

    stride = (out_w + 7) // 8
    data = []
    for line in bits:
        for i in range(stride):
            byte = 0
            for b in range(8):
                x = i * 8 + b
                if x < out_w and line[x]:
                    byte |= 0x80 >> b
            data.append(byte)
    rgb565 = lambda c: ((c[0] & 0xF8) << 8) | ((c[1] & 0xFC) << 3) | (c[2] >> 3)

    with open(dst, "w") as f:
        f.write("#pragma once\n\n// Generated by tools/logo2header.py from %s; don't edit by hand.\n"
                "// 1-bit mask (rows padded to bytes, MSB first) plus one RGB565 colour per row.\n\n"
                "#include <Arduino.h>\n\n" % src.split("/")[-1])
        f.write("static const int16_t LOGO_W = %d;\nstatic const int16_t LOGO_H = %d;\n\n" % (out_w, out_h))
        f.write("static const uint16_t LOGO_ROW_COLORS[LOGO_H] PROGMEM = {\n")
        for i in range(0, out_h, 8):
            f.write("    " + ", ".join("0x%04X" % rgb565(c) for c in colors[i:i + 8]) + ",\n")
        f.write("};\n\nstatic const uint8_t LOGO_BITS[LOGO_H * %d] PROGMEM = {\n" % stride)
        for y in range(out_h):
            f.write("    " + ", ".join("0x%02X" % b for b in data[y * stride:(y + 1) * stride]) + ",\n")
        f.write("};\n")
    print("logo %dx%d from source box %dx%d" % (out_w, out_h, x1 - x0, y1 - y0))

    if preview:
        z = 4
        write_png(preview, out_w * z, out_h * z,
                  lambda x, y: colors[y // z] if bits[y // z][x // z] else (0, 0, 0))


if __name__ == "__main__":
    main()
